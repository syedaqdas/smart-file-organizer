"""AI Storage Assistant module.

Analyzes discovered files, detects storage bloat, stale assets,
large files, and generates actionable optimization recommendations.
"""

from dataclasses import dataclass, field
from datetime import datetime, timedelta
from pathlib import Path
from typing import Dict, List, Optional
from collections import defaultdict

from .scanner import ScanSummary, FileInfo, format_file_size


@dataclass
class StorageInsight:
    """Individual recommendation or finding from the assistant."""
    type: str  # 'warning', 'tip', 'cleanup', 'info'
    title: str
    description: str
    icon: str
    impact: str = "Medium"  # 'Low', 'Medium', 'High'
    potential_savings: Optional[str] = None


@dataclass
class AssistantAnalysis:
    """Comprehensive intelligence report generated for a scanned folder."""
    total_files: int
    total_size_formatted: str
    summary_headline: str
    largest_files: List[FileInfo] = field(default_factory=list)
    stale_files: List[FileInfo] = field(default_factory=list)
    duplicate_names: Dict[str, List[FileInfo]] = field(default_factory=dict)
    insights: List[StorageInsight] = field(default_factory=list)
    category_percentages: Dict[str, float] = field(default_factory=dict)


def analyze_storage(
    summary: ScanSummary,
    stale_days_threshold: int = 90,
    top_largest_limit: int = 5,
) -> AssistantAnalysis:
    """Examines a ScanSummary and produces intelligent storage optimization insights.

    Args:
        summary: The ScanSummary generated by scanning a folder.
        stale_days_threshold: Age in days to qualify a file as stale. Defaults to 90 days.
        top_largest_limit: Number of top space hogs to report. Defaults to 5.

    Returns:
        AssistantAnalysis containing actionable suggestions and file breakdowns.
    """
    total_files = summary.total_files
    total_size = summary.total_size_bytes
    insights: List[StorageInsight] = []

    if total_files == 0:
        return AssistantAnalysis(
            total_files=0,
            total_size_formatted="0 B",
            summary_headline="Folder is currently empty. No optimization needed.",
        )

    # 1. Calculate category percentages
    category_percentages: Dict[str, float] = {}
    if total_size > 0:
        for cat, size in summary.category_sizes.items():
            pct = (size / total_size) * 100
            category_percentages[cat] = round(pct, 1)

    # 2. Identify top largest files
    sorted_by_size = sorted(summary.files, key=lambda f: f.size_bytes, reverse=True)
    largest_files = sorted_by_size[:top_largest_limit]

    # 3. Identify stale files
    cutoff_date = datetime.now() - timedelta(days=stale_days_threshold)
    stale_files = [f for f in summary.files if f.modified_time < cutoff_date]

    # 4. Identify potential duplicate filenames across subfolders
    name_map = defaultdict(list)
    for f in summary.files:
        name_map[f.name.lower()].append(f)
    duplicate_names = {name: flist for name, flist in name_map.items() if len(flist) > 1}

    # --------------------------------------------------------------------------
    # Generate Heuristic Intelligence Insights
    # --------------------------------------------------------------------------

    # Insight A: Video/Media dominance
    video_pct = category_percentages.get("Videos", 0.0)
    video_size = summary.category_sizes.get("Videos", 0)
    if video_pct >= 40.0 and video_size > 50 * 1024 * 1024:  # > 50 MB
        insights.append(StorageInsight(
            type="warning",
            title="Heavy Video Storage Concentration",
            description=(
                f"Videos account for {video_pct}% ({format_file_size(video_size)}) of total disk usage in this folder. "
                "Consider compressing large video files or offloading them to external/cloud cold storage."
            ),
            icon="🎬",
            impact="High",
            potential_savings=format_file_size(int(video_size * 0.4)),
        ))

    # Insight B: Stale files clutter
    if len(stale_files) > 0:
        stale_size = sum(f.size_bytes for f in stale_files)
        insights.append(StorageInsight(
            type="cleanup",
            title=f"Detected {len(stale_files)} Stale Files (> {stale_days_threshold} days old)",
            description=(
                f"You have {len(stale_files)} files totaling {format_file_size(stale_size)} that haven't been modified "
                f"in over {stale_days_threshold} days. Organizing or archiving these will clear visual clutter."
            ),
            icon="⏳",
            impact="Medium",
            potential_savings=format_file_size(stale_size),
        ))

    # Insight C: Archive accumulation
    archive_size = summary.category_sizes.get("Archives", 0)
    archive_count = summary.category_counts.get("Archives", 0)
    if archive_count >= 3 or archive_size > 100 * 1024 * 1024:
        insights.append(StorageInsight(
            type="tip",
            title=f"Review {archive_count} Compressed Archives",
            description=(
                f"Archives take up {format_file_size(archive_size)}. If these zip/tar/rar archives are already extracted, "
                "deleting the redundant archive files can immediately free up disk space."
            ),
            icon="📦",
            impact="Medium",
            potential_savings=format_file_size(archive_size),
        ))

    # Insight D: Duplicate filename clashes
    if duplicate_names:
        total_dups = sum(len(flist) for flist in duplicate_names.values())
        insights.append(StorageInsight(
            type="warning",
            title=f"{len(duplicate_names)} Duplicate Filename Groups Found",
            description=(
                f"Found {total_dups} files across different folders sharing identical names. "
                "Smart File Organizer's collision safety will automatically rename them to prevent overwrites."
            ),
            icon="🛡️",
            impact="High",
        ))

    # Insight E: Top heavy file notice
    if largest_files and largest_files[0].size_bytes > 20 * 1024 * 1024:  # > 20 MB
        top_f = largest_files[0]
        insights.append(StorageInsight(
            type="info",
            title=f"Largest Single File: {top_f.name}",
            description=f"This file consumes {top_f.size_formatted} ({top_f.category}). Verify if it belongs in cold storage.",
            icon="🐘",
            impact="Low",
        ))

    # Insight F: Positive organization tip
    insights.append(StorageInsight(
        type="tip",
        title="Automated Category Segregation",
        description=(
            f"Organizing {total_files} files into dedicated folders will streamline searchability and system index performance."
        ),
        icon="✨",
        impact="Low",
    ))

    # Overall headline
    headline = (
        f"Analyzed {total_files} files ({summary.total_size_formatted}). "
        f"{len(insights)} storage optimization recommendations identified."
    )

    return AssistantAnalysis(
        total_files=total_files,
        total_size_formatted=summary.total_size_formatted,
        summary_headline=headline,
        largest_files=largest_files,
        stale_files=stale_files,
        duplicate_names=duplicate_names,
        insights=insights,
        category_percentages=category_percentages,
    )
